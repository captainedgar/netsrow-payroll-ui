export function computeTenantMonthlyBreakdown(
  tenant: TenantRecord,
  modules: SaasModule[],
  planCatalog: SaasPlan[]
): {
  baseDop: number;
  addons: { code: SaasModuleCode; nameEs: string; nameEn: string; priceDop: number }[];
  includedModules: SaasModuleCode[];
  totalDop: number;
} {
  const plan = planCatalog.find((p) => p.id === tenant.planId);
  const includedSet = new Set<SaasModuleCode>(plan?.includedModules ?? ['CORE_ERP']);
  const baseDop = tenant.contractedBasePriceDop;

  const addons: { code: SaasModuleCode; nameEs: string; nameEn: string; priceDop: number }[] = [];
  tenant.enabledModules.forEach((modCode) => {
    if (includedSet.has(modCode)) return;
    const modDef = modules.find((m) => m.code === modCode);
    if (!modDef) return;
    const agreedFee = tenant.addonPricesDop[modCode] ?? modDef.monthlyPriceDop;
    if (agreedFee > 0) {
      addons.push({
        code: modCode,
        nameEs: modDef.nameEs,
        nameEn: modDef.nameEn,
        priceDop: agreedFee,
      });
    }
  });

  const addonsSum = addons.reduce((acc, a) => acc + a.priceDop, 0);
  return {
    baseDop,
    addons,
    includedModules: Array.from(includedSet),
    totalDop: baseDop + addonsSum,
  };
}

