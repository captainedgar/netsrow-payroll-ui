function makeSeedInvoice(
  partial: Omit<
    ElectronicInvoice,
    | 'trackId'
    | 'securityCode'
    | 'qrPayloadUrl'
    | 'xmlContent'
    | 'signatureAlgorithm'
    | 'certificateSerial'
  >,
  company: CompanyProfile
): ElectronicInvoice {
  const securityCode = buildDeterministicSecurityCode(
    `${partial.eNcf}-${partial.buyerRnc}-${partial.totalAmount.toFixed(2)}`
  );
  const trackId = buildTrackId(partial.ecfType, partial.eNcf);
  const qrPayloadUrl = buildEcfQrUrl({
    emitterRnc: company.rnc,
    buyerRnc: partial.buyerRnc,
    eNcf: partial.eNcf,
    issueDate: partial.issueDate,
    totalAmount: partial.totalAmount,
    digitalSignatureDate: partial.digitalSignatureDate,
    securityCode,
  });

  const base: Omit<ElectronicInvoice, 'xmlContent'> = {
    ...partial,
    trackId,
    securityCode,
    qrPayloadUrl,
    signatureAlgorithm: 'RSA-SHA256 (XMLDSig)',
    certificateSerial: 'IND-CERT-2026-884192A',
  };

  return {
    ...base,
    xmlContent: buildEcfXml(base, company),
  };
}

